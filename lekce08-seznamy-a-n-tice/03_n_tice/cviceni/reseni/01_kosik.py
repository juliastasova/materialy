# Řešení cvičení 1 – N-tice
# Tvoje řešení může vypadat jinak, a to je v pořádku.

# Do košíku patří trojice: zboží, počet kusů a cena za kus. Rozbal ji
#    do tří proměnných a vypiš větu:
#
#      víno: 3 ks za 450 Kč

polozka = ("víno", 3, 150)

zbozi, kusy, cena = polozka

print(f"{zbozi}: {kusy} ks za {kusy * cena} Kč")
