# Zeptej se uživatele na číslo. Vypiš "Velké číslo!", když je větší
#    než 100, jinak "Malé číslo.".

# Podmienka na vstup od užívateľa
číslo = int(input("Napíš ľubovoľné číslo: "))

if číslo > 100:
    print("Veľké číslo!")
else:
    print("Malé číslo!")
